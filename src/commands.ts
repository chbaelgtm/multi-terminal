export function filterCommands(
  shell: CommandShell,
  category: CommandCategory | '전체',
  query: string,
) {
  const words = query.trim().toLocaleLowerCase().split(/\s+/).filter(Boolean);
  return commands.filter((command) => {
    if (command.shell !== shell || (category !== '전체' && command.category !== category))
      return false;
    const text = [
      command.title,
      command.example,
      command.description,
      command.category,
      ...(command.aliases ?? []),
    ]
      .join(' ')
      .toLocaleLowerCase();
    return words.every((word) => text.includes(word));
  });
}
